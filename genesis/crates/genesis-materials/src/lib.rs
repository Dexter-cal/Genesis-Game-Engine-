// ─── The Master Material ──────────────────────────────────────────────────────

/// The complete material definition for any surface in Genesis
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Material {
    pub id: String,
    pub name: String,
    pub material_type: MaterialType,

    // ─── PBR Core ────────────────────────────────────────────────────────────
    /// Base color / albedo (sRGB)
    pub albedo: TextureRef,
    pub albedo_tint: [f32; 4],
    /// Tangent-space normal map
    pub normal: TextureRef,
    pub normal_strength: f32,
    pub normal_map_format: NormalMapFormat,
    /// Roughness (0=mirror, 1=fully rough)
    pub roughness: TextureRef,
    pub roughness_value: f32,
    /// Metallic (0=dielectric, 1=conductor)
    pub metallic: TextureRef,
    pub metallic_value: f32,
    /// Ambient occlusion
    pub ao: TextureRef,
    pub ao_strength: f32,
    /// Emissive (self-illumination)
    pub emissive: TextureRef,
    pub emissive_color: [f32; 3],
    pub emissive_strength: f32,
    /// Height / displacement
    pub height: TextureRef,
    pub height_scale: f32,
    pub height_bias: f32,
    pub parallax_mode: ParallaxMode,

    // ─── Transparency ────────────────────────────────────────────────────────
    pub opacity: TextureRef,
    pub opacity_value: f32,
    pub blend_mode: BlendMode,
    pub alpha_cutoff: f32,
    pub alpha_dither: bool,
    pub alpha_to_coverage: bool,

    // ─── Advanced PBR ────────────────────────────────────────────────────────
    /// Transmission (glass, cloth) 0-1
    pub transmission: f32,
    pub transmission_color: [f32; 3],
    pub ior: f32,             // Index of refraction (glass=1.5, diamond=2.4)
    pub refraction_scale: f32,

    /// Sub-surface scattering (skin, wax, marble)
    pub sss_enabled: bool,
    pub sss_color: [f32; 3],
    pub sss_radius: [f32; 3], // per-channel falloff radius
    pub sss_profile: SssProfile,
    pub sss_anisotropy: f32,
    pub sss_strength: f32,

    /// Clearcoat (car paint, lacquer, varnish)
    pub clearcoat: f32,
    pub clearcoat_roughness: f32,
    pub clearcoat_normal: TextureRef,

    /// Sheen (fabric, cloth)
    pub sheen: f32,
    pub sheen_roughness: f32,
    pub sheen_color: [f32; 3],

    /// Iridescence (soap bubble, thin film, beetle wings, pearl)
    pub iridescence: f32,
    pub iridescence_ior: f32,
    pub iridescence_thickness_min: f32,
    pub iridescence_thickness_max: f32,

    /// Anisotropy (brushed metal, hair, satin)
    pub anisotropy: f32,
    pub anisotropy_rotation: f32,
    pub anisotropy_map: TextureRef,

    // ─── Special Material Params ─────────────────────────────────────────────
    pub special: SpecialMaterialParams,

    // ─── Rendering ───────────────────────────────────────────────────────────
    pub two_sided: bool,
    pub cull_mode: CullMode,
    pub depth_write: bool,
    pub depth_test: bool,
    pub depth_bias: f32,
    pub wireframe: bool,
    pub cast_shadow: bool,
    pub receive_shadow: bool,
    pub receive_decals: bool,
    pub receive_ao: bool,
    pub vertex_color_multiplier: bool,

    // ─── UV ──────────────────────────────────────────────────────────────────
    pub uv: UvSettings,
    pub uv_channel_albedo: u32,
    pub uv_channel_normal: u32,
    pub uv_channel_roughness: u32,
    pub uv_channel_ao: u32,

    // ─── Tessellation ────────────────────────────────────────────────────────
    pub tessellation: Option<TessellationSettings>,

    // ─── Wind Response ───────────────────────────────────────────────────────
    pub wind_response: Option<WindMaterialResponse>,

    // ─── Tags ────────────────────────────────────────────────────────────────
    pub tags: Vec<String>,
    pub custom_params: HashMap<String, f32>,
    pub shader_graph_id: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum NormalMapFormat { OpenGl, DirectX }

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum ParallaxMode {
    None,
    Simple,
    POM { min_samples: u32, max_samples: u32 }, // Parallax Occlusion Mapping
    Relief { steps: u32 },
    Displacement, // actual geometry displacement (requires tessellation)
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum BlendMode {
    Opaque,
    AlphaTest,
    AlphaBlend,
    Additive,
    Multiply,
    Screen,
    Premultiplied,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum CullMode { Back, Front, None }

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum SssProfile {
    Skin,    // Penner skin profile
    Marble,
    Wax,
    Milk,
    Plant,
    Custom { scatter_radius: f32 },
}

// ─── Material Types ───────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum MaterialType {
    /// Standard physically-based material
    Standard,
    /// Toon / cel-shaded (flat colors, outlines)
    Toon { shade_steps: u32, outline_width: f32, outline_color: [f32; 4] },
    /// Hair (Kajiya-Kay dual scattering)
    Hair { primary_shift: f32, secondary_shift: f32, primary_specular: f32, secondary_specular: f32 },
    /// Human / character skin (SSS preset)
    Skin { skin_tone: [f32; 4], subsurface_weight: f32 },
    /// Eyes (cornea, iris, pupil)
    Eye { ior: f32, iris_scale: f32, pupil_size: f32, sclera_roughness: f32 },
    /// Fabric
    Fabric { fabric_type: FabricType },
    /// Water / liquid surface
    Water { wave_normal: Option<String>, foam_texture: Option<String>, depth_color: [f32; 4] },
    /// Glass / refraction
    Glass { tint: [f32; 4], frosted: bool, thickness: f32 },
    /// Foliage (two-sided, wind, translucency)
    Foliage { translucency: f32, subsurface_color: [f32; 3], wind_influence: f32 },
    /// Terrain (multi-layer blend up to 8 layers)
    Terrain { layers: Vec<TerrainMaterialLayer> },
    /// Decal (projected onto geometry)
    Decal { opacity: f32, affects_albedo: bool, affects_normal: bool, affects_roughness: bool },
    /// Particle (billboard, GPU-optimized)
    Particle { soft_particle: bool, soft_particle_fade: f32 },
    /// Hologram / energy shield
    Hologram { scan_line_density: f32, edge_glow: f32, distortion: f32 },
    /// Lava / magma
    Lava { flow_speed: f32, hot_color: [f32; 4], cool_color: [f32; 4] },
    /// Unlit (no lighting calculation)
    Unlit,
    /// Custom shader graph
    Custom { shader_graph_id: String },
}

