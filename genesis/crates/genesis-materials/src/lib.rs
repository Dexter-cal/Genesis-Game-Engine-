// ─── Wind Response ────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WindMaterialResponse {
    pub mode: WindMode,
    pub strength: f32,
    pub frequency: f32,
    pub bend_height: f32,     // how high up bending starts (0 = root, 1 = tip)
    pub turbulence: f32,
    pub leaf_ripple: bool,    // secondary small motion for leaves
    pub leaf_ripple_strength: f32,
    pub stiffness: f32,       // how quickly it returns to rest
    pub wind_texture: Option<String>, // flow map for complex wind patterns
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum WindMode {
    Simple,    // single direction sway
    Foliage,   // grass/shrub bending
    Tree,      // trunk + branch + leaf separation
    Cloth,     // connected to cloth simulation
    Palm,      // tropical palm tree movement
}

