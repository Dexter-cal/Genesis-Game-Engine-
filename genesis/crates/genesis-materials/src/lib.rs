//! Genesis Material System
//!
//! Complete PBR material system covering every rendering use case:
//!
//! MATERIAL TYPES:
//! - Standard PBR (Metallic-Roughness workflow)
//! - Specular-Glossiness PBR (legacy workflow)
//! - Unlit (UI, skybox, emissive only)
//! - Toon / Cel-Shaded
//! - Hair (Kajiya-Kay + dual scattering)
//! - Skin (Sub-Surface Scattering)
//! - Eyes (cornea refraction, iris parallax)
//! - Fabric / Cloth (cotton, silk, velvet, leather)
//! - Liquid (water, slime, blood, lava)
//! - Glass / Refraction
//! - Foliage (two-sided, translucency)
//! - Terrain (multi-layer blend)
//! - Decal (projected onto other surfaces)
//! - Post-Process (screen-space effects)
//!
//! TEXTURE MAPS:
//! - Albedo / Base Color (RGB + Alpha)
//! - Normal Map (tangent-space DirectX or OpenGL)
//! - Roughness (R channel)
//! - Metallic (G channel)
//! - Ambient Occlusion (B channel)
//! - Emissive (RGB)
//! - Height / Displacement (parallax occlusion)
//! - Opacity (A or separate)
//! - Transmission (for glass/cloth)
//! - Subsurface Color + Radius
//! - Anisotropy (brushed metal, hair)
//! - Clearcoat (car paint, lacquer)
//! - Sheen (fabric)
//! - Iridescence (soap bubble, thin film)
//!
//! PROCEDURAL TEXTURES:
//! - Noise (Perlin, Simplex, Voronoi, FBM)
//! - Checker, Brick, Gradient, Wave
//! - Rust, Grunge, Scratches, Dirt layers
//! - Weather damage (rain streaks, moss, cracks)

